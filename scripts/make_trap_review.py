"""Write eval/raw/trap_review.md: a hand-check sheet for every trap question (Step 3b).

For each trap it searches the whole book (body and index, lines 33-9433 of the
original file) for the trap's own search terms and for the core words of its
missing item, and quotes the nearest passages. The reviewer reads each entry
and ticks the box; scripts/check_evalset.py sets verified_absent only for
ticked traps.

Usage: python scripts/make_trap_review.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BOOK = ROOT / "data/books/The Handbook of Soap Manufacture.txt"
TRAPS = ROOT / "eval/raw/trap.jsonl"
OUT = ROOT / "eval/raw/trap_review.md"
FIRST, LAST = 33, 9433  # 1-based lines of the book (body + index); later lines are adverts and Gutenberg notices

STOP = set("""a an and the of for in on to by with from at as or per its their his her this that these those
what which who whom how does do did is are was were be been give given gives author authors book
use used using about into than between over under any each other some""".split())
COMMON = 15   # a core word with more hits than this is reported as common, without line numbers
CONTEXT = 2   # lines of context either side of a quoted hit
MAX_QUOTES = 3


def norm(s):
    s = s.lower().replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    s = s.replace("—", " ").replace("-", " ")
    return re.sub(r"\s+", " ", s)


lines = BOOK.read_text(encoding="utf-8").splitlines()
book_lines = lines[FIRST - 1:LAST]
# One normalised string with a map from character offset to line number, so phrases split across lines still match
text, starts = "", []
for i, ln in enumerate(book_lines):
    starts.append(len(text))
    text += norm(ln) + " "


def line_of(pos):
    lo, hi = 0, len(starts) - 1
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if starts[mid] <= pos:
            lo = mid
        else:
            hi = mid - 1
    return FIRST + lo


def hits(term, whole_word=False):
    t = re.escape(norm(term).strip())
    pat = rf"\b{t}\b" if whole_word else t
    return sorted({line_of(m.start()) for m in re.finditer(pat, text)})


def quote(line_no):
    a, b = max(FIRST, line_no - CONTEXT), min(LAST, line_no + CONTEXT)
    body = "\n".join(f"    {n}: {lines[n - 1]}" for n in range(a, b + 1))
    return body


def fmt(term, found):
    if not found:
        return f"`{term}` (0)"
    if len(found) > COMMON:
        return f"`{term}` ({len(found)}, common)"
    return f"`{term}` ({len(found)}: lines {', '.join(map(str, found))})"


traps = [json.loads(l) for l in TRAPS.read_text(encoding="utf-8").splitlines() if l.strip()]
out = [
    "# Trap hand-check (Step 3b)",
    "",
    "Generated by `scripts/make_trap_review.py` from `eval/raw/trap.jsonl` and the original book file "
    f"(lines {FIRST}-{LAST}: body and index). Search is case-insensitive and ignores line breaks and hyphens.",
    "",
    "**How to check each trap:**",
    "- **absent_topic:** the subject must not appear anywhere in the book. Search-term hits should be 0; "
    "core-word hits must be coincidental (a different subject).",
    "- **absent_detail:** the subject is in the book, but the asked-for detail (figure, name, method) must not be. "
    "Read the quoted passages; if needed, open the book at those lines.",
    "- Tick `[x]` only if the book cannot answer the question. If it can, leave it unticked and write why in Notes; "
    "the trap is then dropped or replaced (logged in `EDITS.md`).",
    "",
]
n_hit = 0
for t in traps:
    term_hits = {s: hits(s) for s in t["absence_search_terms"]}
    words = [w for w in re.findall(r"[a-z]+", norm(t["missing_item"])) if w not in STOP and len(w) > 3]
    word_hits = {w: hits(w, whole_word=True) for w in dict.fromkeys(words)}
    any_term = any(term_hits.values())
    n_hit += any_term

    # Nearest passages: search-term hits first, then the rarest core words
    quote_lines = []
    for s, f in term_hits.items():
        quote_lines += f
    for w, f in sorted(word_hits.items(), key=lambda kv: len(kv[1])):
        if 0 < len(f) <= COMMON:
            quote_lines += f
    seen, picked = set(), []
    for n in quote_lines:
        if all(abs(n - p) > 2 * CONTEXT for p in seen):
            picked.append(n)
            seen.add(n)
        if len(picked) == MAX_QUOTES:
            break

    flag = "search terms found: read carefully" if any_term else "no search-term hits"
    out += [
        f"## {t['id']} ({t['split']}, {t['kind']}): {t['missing_item']}",
        "",
        f"**Question:** {t['question']}",
        "",
        f"**Nearest section (writer):** {t['nearest_section']}",
        "",
        f"**Search terms** ({flag}): " + "; ".join(fmt(s, f) for s, f in term_hits.items()),
        "",
        "**Core words:** " + ("; ".join(fmt(w, f) for w, f in word_hits.items()) or "none"),
        "",
    ]
    if picked:
        out.append("**Nearest passages:**")
        out.append("")
        for n in picked:
            out += ["```", quote(n), "```"]
        out.append("")
    out += ["- [ ] Verified absent (the book cannot answer this question)", "", "Notes:", "", "---", ""]

OUT.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(traps)} traps, {n_hit} with search-term hits")
